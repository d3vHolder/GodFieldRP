-- GodField/tools/bundle.lua
-- Release-side build script. Not shipped with the library.
--
-- Usage (from the GodField root):
--   lua tools/bundle.lua
--
-- Reads every module in ORDER, inlines its body into a single file, and
-- emits build/godfield.lua and build/godfield.min.lua.
--
-- The emitted file exposes the same `GodField` table as `init.lua`, so a
-- user can load either one with the same `loadstring(...)()` call.

local ORDER = {
    "lib/Util.lua",
    "lib/Signals.lua",
    "lib/Store.lua",
    "lib/Theme.lua",
    "lib/Icons.lua",
    "lib/Create.lua",
    "ui/Window.lua",
    "ui/Tab.lua",
    "ui/Section.lua",
    "elements/init.lua",
    "elements/Button.lua",
    "elements/Toggle.lua",
    "elements/Slider.lua",
    "elements/Input.lua",
    "elements/Keybind.lua",
    "elements/Dropdown.lua",
    "elements/ColorPicker.lua",
    "elements/Label.lua",
    "elements/Paragraph.lua",
    "elements/SectionTitle.lua",
    "elements/Divider.lua",
    "lib/Config.lua",
    "lib/Reporter.lua",
}

-- ── Helpers ──────────────────────────────────────────────────────────

local function readFile(p)
    local f = assert(io.open(p, "rb"), "bundle: cannot open " .. p)
    local s = f:read("*a")
    f:close()
    return s
end

local function writeFile(p, s)
    local f = assert(io.open(p, "wb"), "bundle: cannot write " .. p)
    f:write(s)
    f:close()
end

local function ensureDir(p)
    -- Portable enough for the release machine: try mkdir, ignore failure
    -- (folder already exists).
    local ok = os.execute(
        (package.config:sub(1, 1) == "\\")
            and ("if not exist \"" .. p .. "\" mkdir \"" .. p .. "\"")
            or  ("mkdir -p '" .. p .. "' 2>/dev/null")
    )
    return ok
end

-- ── Read every module in load order ──────────────────────────────────

local modules = {}
for _, path in ipairs(ORDER) do
    local body = readFile(path)
    modules[path] = body
end

-- ── Emit the single-file build ───────────────────────────────────────
--
-- Every module is stored as a string in EMBEDDED, keyed by its path. The
-- loader runs `loadstring(EMBEDDED[path])()` to execute it, exactly as
-- init.lua's fetch() does for URLs. This keeps the build identical in
-- behaviour to the multi-file tree.

local HEADER = [[
-- GodField single-file build — generated by tools/bundle.lua.
-- Do not edit by hand. Regenerate from source modules.
-- Version: 2.0.0

local GodField = { Version = "2.0.0" }
local EMBEDDED = {}

]]

local parts = { HEADER }

for _, path in ipairs(ORDER) do
    -- %q escapes the body so it can sit inside a Lua long-string or a
    -- quoted literal; %q is robust for arbitrary Lua source. We use a
    -- long-bracket wrapper to keep the emitted file readable.
    local body = modules[path]
    -- Guard: if the source itself contains ]] we have to escape. Rare in
    -- practice but cheap to handle.
    local safe = body:gsub("%]%]", "]=]")
    parts[#parts + 1] = ("EMBEDDED[%q] = [==[\n%s]==]\n"):format(path, safe)
end

parts[#parts + 1] = [[
-- ── Loader ─────────────────────────────────────────────────────────
local function fetch(name)
    local src = EMBEDDED[name]
    if not src then error("GodField: missing embedded module " .. name, 2) end
    local ok, mod = pcall(function() return (loadstring(src) :: any)() end)
    if not ok then error("GodField: " .. name .. " failed: " .. tostring(mod), 2) end
    return mod
end

local modules = {
    Util    = fetch("lib/Util.lua"),
    Signals = fetch("lib/Signals.lua"),
    Store   = fetch("lib/Store.lua"),
    Theme   = fetch("lib/Theme.lua"),
}
modules.Icons    = fetch("lib/Icons.lua")
modules.Create   = fetch("lib/Create.lua")(modules)
modules.Window   = fetch("ui/Window.lua")({
    Create  = modules.Create,
    Signals = modules.Signals,
    Store   = modules.Store,
    Theme   = modules.Theme,
    Util    = modules.Util,
    Icons   = modules.Icons,
})
modules.Tab      = fetch("ui/Tab.lua")({
    Signals  = modules.Signals,
    Theme    = modules.Theme,
    Util     = modules.Util,
    Icons    = modules.Icons,
    Elements = fetch("elements/init.lua")(modules),
})
modules.Section  = fetch("ui/Section.lua")({ Util = modules.Util })
modules.Config   = fetch("lib/Config.lua")({ Util = modules.Util, Store = modules.Store })
modules.Reporter = fetch("lib/Reporter.lua")({ Util = modules.Util })

for k, v in pairs(modules) do GodField[k] = v end

function GodField:CreateWindow(settings)
    return modules.Window.new(settings, modules)
end

return GodField
]]

local full = table.concat(parts, "\n")

-- ── Write build/ ─────────────────────────────────────────────────────

ensureDir("build")
writeFile("build/godfield.lua", full)

-- A crude minifier: strip whole-line comments and collapse blank lines.
-- Not a real minifier; it exists so the shipped file is smaller, not
-- obfuscated.
local min = full
    :gsub("%-%-[^\n]*\n", "\n")
    :gsub("\n\n+", "\n")
writeFile("build/godfield.min.lua", min)

print(("GodField bundle: %d bytes (min %d)"):format(#full, #min))